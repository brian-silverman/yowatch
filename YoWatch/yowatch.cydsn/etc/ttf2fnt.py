#!/usr/local/bin/python3
#
# ttf2fnt.py - convert a OS TTF font to a YoWatch fnt file.
#
# Usage:
#
#   ./ttf2fnt.py <font> <pointsize> <ords...>
#
# where:
#   font
#       is a system font.  See list with "convert -list font".  If no fonts
#       appear on macos, you may need to use ImageMagick's "imagick_type_gen"
#       script.
#   pointsize
#       the pointsize of the TTF font to use.  This will generally create a
#       YoWatch font whose height is 10-20% less than the point size.
#   ords
#       A list of ASCII ordinals of characters to use for this font.  Only use
#       chars you need, as each char wastes space.  For convienece, it's
#       suggested to use the bash shell's {n..m} glob feature.
#
# Example:
#   ./etc//ttf2fnt.py CourierNewB 80 {48..58} > fonts/font_mybigfont.fnt
# would convert the CourierNewB (bold) font to 80 point for "0123456789:"
#   
import os
import tempfile
import subprocess
import sys
import re

font, pointsize  = sys.argv[1:3]
ords = [int(i) for i in sys.argv[3:]]
chrs = sorted([chr(i) for i in ords])

#
# label is the string of whitespace separated chars to print.  Note: additional
# whitespace at end is needed or else "convert" erroneously crops a few pixels
# off edge of last char.
#
label = " ".join(chrs) + " "

fd, temppath = tempfile.mkstemp()
try:
    cmd = \
        'convert -font {:s} -pointsize {:s} label:"{:s}" ' \
        '-trim -bordercolor white -border 1x0 -depth 8 -identify rgb:{:s}'
    out = subprocess.check_output(cmd.format(font, pointsize, label, temppath), shell=True)

    #
    # convert's -identify flag outputs a line of the format, for example:
    #   label:A =>A  LABEL 60x59=>33x30 60x59+0+12 8-bit sRGB 0.000u 0:00.000
    # we want the font height, which in the example above is the 30.
    #
    match = re.search('\\b\d+x\d+=>\d+x(\d+)\\b', str(out))
    assert match
    height = int(match.group(1))

    with os.fdopen(fd, 'rb') as f:
        data = f.read()
finally:
    os.remove(temppath)


#
# data is in RGB 8:8:8 format (depth 8).  As fonts are grayscale, R==G==B, so
# we can decimate by 3.
#
flattened_bitmap = [int(d) for d in data[::3]]

#
# Remap colors.  Fonts are black on white.  We want white on black.  In
# addition, we'll convert from 8 bit color to 4 bit.
#
flattened_bitmap = [0xF - (p>>4) for p in flattened_bitmap]

#
# Unflatten
#
assert len(flattened_bitmap) % height == 0
width = int(len(flattened_bitmap) / height)
bitmap = [[flattened_bitmap[y*width+x] for x in range(width)] for y in range(height)]

#
# Split bitmap into chars.  Each char is separated by some whitespace.  To
# simplyfy processing, there's also addition whitespace before and after the
# set of chars.
#
transposed_bitmap = list(zip(*bitmap))
char_bitmaps = [0]*128
col = 0
for o in ords:
    # Skip all white columns
    while all(x==0 for x in transposed_bitmap[col]):
        col += 1
    start = col

    # Find last non-white column
    while not all(x==0 for x in transposed_bitmap[col]):
        col += 1
    end = col

    char_bitmaps[o] = list(zip(*transposed_bitmap[start:end]))

#
# Output .fnt file header
#
preheader = """
# Autogenerated font by ttf2font command:
#
#   {:s}
#
""".format(" ".join(sys.argv))
header = """
{
    '0': GRAY_0X0,
    '1': GRAY_0X1,
    '2': GRAY_0X2,
    '3': GRAY_0X3,
    '4': GRAY_0X4,
    '5': GRAY_0X5,
    '6': GRAY_0X6,
    '7': GRAY_0X7,
    '8': GRAY_0X8,
    '9': GRAY_0X9,
    'a': GRAY_0XA,
    'b': GRAY_0XB,
    'c': GRAY_0XC,
    'd': GRAY_0XD,
    'e': GRAY_0XE,
    'f': GRAY_0XF,
}
"""
print(preheader)
print(header)
print("=====")

#
# Output .fnt file character map
#
for row in range(8):
    for subrow in range(height):
        for col in range(16):
            char_bitmap = char_bitmaps[row*16+col]
            if not char_bitmap:
                char_bitmap = char_bitmaps[ords[0]]
            for pixel in char_bitmap[subrow]:
                print(hex(pixel)[-1], end="")
            print(" | " if col < 15 else "", end="")
        print()
    print()

            





